function neighbors = get_neighbors(x, y, N)

    % Write this function

    % list all possible neighbors
    neighbors = [...
        x-1 y-1; ...
        x-1 y; ...
        x-1 y+1; ...
        x   y-1; ...
        x   y+1; ...
        x+1 y-1; ...
        x+1 y; ...
        x+1 y+1; ...
        ];

    row = 1;
    % eliminate neighbors outside the grid
    while row <= height(neighbors)
        if any(neighbors(row,:) < 1) || any(neighbors(row,:) > N)
            neighbors(row,:) = [];
        else
            row = row + 1;
        end
    end

end